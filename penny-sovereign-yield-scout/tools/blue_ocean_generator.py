# ─── FastAPI scaffold template ────────────────────────────────────────────────

API_MAIN_TEMPLATE = '''\
#!/usr/bin/env python3
"""
{{name}} — FastAPI yield server
Auto-generated by blue_ocean_generator.py
Freedom Angel Corp / Audrey Evans
"""
from __future__ import annotations
import os
from datetime import datetime, timezone

import httpx
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel

load_dotenv()

app = FastAPI(
    title="{{name}}",
    description="Auto-generated FastAPI yield server",
    version="1.0.0",
)

DEFILLAMA_BASE = os.getenv("DEFILLAMA_BASE_URL", "https://yields.llama.fi")


class CompoundRequest(BaseModel):
    protocol: str
    pool_id: str
    wallet: str


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "timestamp": datetime.now(timezone.utc).isoformat()}


@app.get("/pools")
def get_pools(protocol: str = "") -> dict:
    """Fetch live pool data from DeFiLlama."""
    try:
        resp = httpx.get(f"{DEFILLAMA_BASE}/pools", timeout=30)
        resp.raise_for_status()
        data = resp.json().get("data", [])
        if protocol:
            data = [p for p in data if protocol.lower() in p.get("project", "").lower()]
        return {"count": len(data), "pools": data[:50]}
    except Exception as exc:
        raise HTTPException(status_code=502, detail=str(exc)) from exc


@app.post("/compound")
def compound(req: CompoundRequest) -> dict:
    """Trigger a compound action (stub — wire to web3 in production)."""
    return {
        "status": "queued",
        "protocol": req.protocol,
        "pool_id": req.pool_id,
        "wallet": req.wallet,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "note": "Connect web3 signer to execute on-chain.",
    }


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port={{port}})
'''

