DEFILLAMA_BASE = os.getenv("DEFILLAMA_BASE_URL", "https://yields.llama.fi")


def fetch_pools(protocol: str) -> list[dict]:
    """Fetch yield pools for a specific protocol from DeFiLlama."""
    resp = httpx.get(f"{DEFILLAMA_BASE}/pools", timeout=30)
    resp.raise_for_status()
    data = resp.json().get("data", [])
    return [p for p in data if protocol.lower() in p.get("project", "").lower()]


def display_pools(pools: list[dict], top: int = 10) -> None:
    table = Table(title=f"{{name}} — Top Pools", show_lines=True)
    table.add_column("#", style="dim", width=3)
    table.add_column("Pool", style="bold cyan")
    table.add_column("Chain", style="white")
    table.add_column("APY", style="bold yellow")
    table.add_column("TVL (USD)", style="white")

    pools_sorted = sorted(pools, key=lambda p: p.get("apy", 0) or 0, reverse=True)
    for i, pool in enumerate(pools_sorted[:top], 1):
        table.add_row(
            str(i),
            pool.get("symbol", "—"),
            pool.get("chain", "—"),
            f"{pool.get('apy', 0):.2f}%" if pool.get("apy") else "—",
            f"${pool.get('tvlUsd', 0):,.0f}",
        )
    console.print(table)


def main() -> None:
    parser = argparse.ArgumentParser(description="{{name}} — {{protocol}} yield CLI")
    parser.add_argument("--top", type=int, default=10)
    parser.add_argument("--output", type=str)
    args = parser.parse_args()

    console.rule("[bold cyan]{{name}}[/]")
    pools = fetch_pools("{{protocol}}")
    display_pools(pools, top=args.top)

    if args.output:
        with open(args.output, "w") as f:
            json.dump(pools[: args.top], f, indent=2)
        console.print(f"Saved to [cyan]{args.output}[/]")


if __name__ == "__main__":
    main()
