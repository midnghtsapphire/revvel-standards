# ─── PDF report generator ─────────────────────────────────────────────────────

def generate_pdf_report(title: str, data_path: str | None, output_dir: Path) -> Path:
    """Generate a glassmorphic-style PDF yield report."""
    try:
        from fpdf import FPDF  # type: ignore

        data: list[dict] = []
        if data_path:
            with open(data_path, encoding="utf-8") as f:
                data = json.load(f)

        pdf = FPDF()
        pdf.add_page()
        pdf.set_auto_page_break(auto=True, margin=15)

        # Header
        pdf.set_fill_color(10, 10, 26)
        pdf.set_text_color(200, 169, 90)
        pdf.set_font("Helvetica", "B", 20)
        pdf.cell(0, 15, title, ln=True, align="C")

        pdf.set_text_color(200, 200, 200)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(
            0, 8,
            f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} | Freedom Angel Corp",
            ln=True, align="C",
        )
        pdf.ln(10)

        # Table header
        pdf.set_fill_color(30, 30, 60)
        pdf.set_text_color(255, 215, 0)
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(10, 8, "#", border=1, fill=True)
        pdf.cell(50, 8, "Protocol", border=1, fill=True)
        pdf.cell(40, 8, "Pool", border=1, fill=True)
        pdf.cell(25, 8, "APY", border=1, fill=True)
        pdf.cell(35, 8, "TVL (USD)", border=1, fill=True)
        pdf.cell(30, 8, "Score", border=1, fill=True, ln=True)

        pdf.set_text_color(220, 220, 220)
        pdf.set_font("Helvetica", "", 8)
        for i, row in enumerate(data[:25], 1):
            fill = (i % 2 == 0)
            if fill:
                pdf.set_fill_color(20, 20, 40)
            else:
                pdf.set_fill_color(15, 15, 30)
            pdf.cell(10, 7, str(i), border=1, fill=True)
            pdf.cell(50, 7, str(row.get("project", "—"))[:25], border=1, fill=True)
            pdf.cell(40, 7, str(row.get("symbol", "—"))[:20], border=1, fill=True)
            apy = row.get("apy")
            pdf.cell(25, 7, f"{apy:.2f}%" if apy else "—", border=1, fill=True)
            tvl = row.get("tvlUsd", 0) or 0
            pdf.cell(35, 7, f"${tvl:,.0f}", border=1, fill=True)
            score = row.get("opportunity_score")
            pdf.cell(30, 7, f"{score:.4f}" if score else "—", border=1, fill=True, ln=True)

        pdf.ln(10)
        pdf.set_text_color(150, 150, 150)
        pdf.set_font("Helvetica", "I", 7)
        pdf.cell(0, 5, "All Rights Reserved. Copyright 2026 Freedom Angel Corp / Audrey Evans.", ln=True, align="C")

        output_path = output_dir / f"{title.lower().replace(' ', '-')}-{datetime.now(timezone.utc).strftime('%Y-%m-%d')}.pdf"
        pdf.output(str(output_path))
        return output_path

    except ImportError:
        console.print("[yellow]fpdf2 not installed. Run: pip install fpdf2[/]")
        # Fallback: write markdown
        output_path = output_dir / f"{title.lower().replace(' ', '-')}.md"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(f"# {title}\n\nGenerated: {datetime.now(timezone.utc).isoformat()}\n\n")
            if data_path:
                f.write(f"Data source: {data_path}\n\n")
                with open(data_path, encoding="utf-8") as df:
                    raw = json.load(df)
                f.write("```json\n" + json.dumps(raw[:10], indent=2) + "\n```\n")
        console.print(f"[yellow]PDF generation requires fpdf2. Saved as Markdown: {output_path}[/]")
        return output_path


# ─── Main generator ───────────────────────────────────────────────────────────

def scaffold_cli(name: str, protocol: str) -> None:
    dest = GENERATED_DIR / name
    dest.mkdir(parents=True, exist_ok=True)
    ctx = {"name": name, "protocol": protocol, "date": datetime.now(timezone.utc).date().isoformat()}

    (dest / "main.py").write_text(render(CLI_MAIN_TEMPLATE, ctx), encoding="utf-8")
    (dest / "requirements.txt").write_text(render(CLI_REQUIREMENTS_TEMPLATE, ctx), encoding="utf-8")
    (dest / "README.md").write_text(render(CLI_README_TEMPLATE, ctx), encoding="utf-8")

    console.print(f"✅ CLI scaffold created at [cyan]{dest}[/]")
    console.print("   Files: main.py, requirements.txt, README.md")


def scaffold_api(name: str, port: int) -> None:
    dest = GENERATED_DIR / name
    dest.mkdir(parents=True, exist_ok=True)
    ctx = {"name": name, "port": str(port)}

    (dest / "main.py").write_text(render(API_MAIN_TEMPLATE, ctx), encoding="utf-8")
    (dest / "Dockerfile").write_text(render(API_DOCKERFILE_TEMPLATE, ctx), encoding="utf-8")
    (dest / ".env.example").write_text(render(API_ENV_TEMPLATE, ctx), encoding="utf-8")
    (dest / "requirements.txt").write_text(render(API_REQUIREMENTS_TEMPLATE, ctx), encoding="utf-8")

    console.print(f"✅ API scaffold created at [cyan]{dest}[/]")
    console.print(f"   Files: main.py, Dockerfile, .env.example, requirements.txt")
    console.print(f"   Start: uvicorn {name}.main:app --reload --port {port}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Blue Ocean Generator — scaffold CLIs, APIs, and PDF reports"
    )
    parser.add_argument("--type", choices=["cli", "api", "pdf"], required=True)
    parser.add_argument("--name", type=str, help="Name for CLI or API scaffold")
    parser.add_argument("--protocol", type=str, default="defi", help="Protocol name (for CLI type)")
    parser.add_argument("--port", type=int, default=8766, help="Port number (for API type)")
    parser.add_argument("--title", type=str, default="Yield Report", help="Report title (for PDF type)")
    parser.add_argument("--data", type=str, help="Path to JSON data file (for PDF type)")

    args = parser.parse_args()
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    reports_dir = GENERATED_DIR / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)

    console.rule("[bold cyan]🌊 Blue Ocean Generator[/]")

    if args.type == "cli":
        if not args.name:
            parser.error("--name is required for --type cli")
        scaffold_cli(args.name, args.protocol)

    elif args.type == "api":
        if not args.name:
            parser.error("--name is required for --type api")
        scaffold_api(args.name, args.port)

    elif args.type == "pdf":
        output_path = generate_pdf_report(args.title, args.data, reports_dir)
        console.print(f"✅ PDF report generated: [cyan]{output_path}[/]")


if __name__ == "__main__":
    main()
