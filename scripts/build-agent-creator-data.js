#!/usr/bin/env node
/**
 * build-agent-creator-data.js
 *
 * Builds the catalog consumed by agent-creator.html (the Agent Hunter
 * dashboard) from the fleet's source-of-truth registries:
 *
 *   - skills/SKILLS_INDEX.yml        -> skills (name, title, category, triggers)
 *   - .github/agent-models.yml       -> model routing profiles
 *   - .github/agent-prompts.yml      -> prompt template names + label triggers
 *   - scripts/openrouter-personas.js -> persona registry
 *
 * Outputs (both generated, both committed):
 *   agent-creator-data.json  — plain JSON, fetched when served over HTTP
 *   agent-creator-data.js    — window.AGENT_CREATOR_DATA wrapper so the
 *                              dashboard also works opened as a local file
 *
 * Usage: node scripts/build-agent-creator-data.js [--out-dir <dir>]
 */

const fs = require("fs");
const path = require("path");
const YAML = require("yaml");

const ROOT = path.resolve(__dirname, "..");

const SOURCES = {
  skills_index: "skills/SKILLS_INDEX.yml",
  model_profiles: ".github/agent-models.yml",
  agent_prompts: ".github/agent-prompts.yml",
  personas: "scripts/openrouter-personas.js",
  fleet: "skills/agentic-workflow-fleet/FLEET.yml",
  security_fleet: "skills/security-fleet/SECURITY_FLEET.yml",
};

function readYaml(rel) {
  return YAML.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
}

// Normalize a fleet source-of-truth YAML (FLEET.yml / SECURITY_FLEET.yml —
// same shape) into the catalog form consumed by the dashboard and by
// scripts/openrouter-personas.js for derived personas.
function shapeFleet(fleetDoc) {
  return {
    name: fleetDoc.fleet,
    version: fleetDoc.version,
    initial_scope: fleetDoc.initial_scope || "",
    charter: fleetDoc.charter || {},
    domains: (fleetDoc.domains || []).map((d) =>
      typeof d === "string"
        ? { name: d, focus: "" }
        : { name: d.name, focus: (d.focus || "").trim() }
    ),
    agents: (fleetDoc.agents || []).map((a) => ({
      handle: a.handle,
      name: a.name,
      pattern: a.pattern,
      group: a.group || "",
      job: (a.job || "").trim(),
      use_for: a.use_for || [],
    })),
  };
}

function buildData() {
  const index = readYaml(SOURCES.skills_index);
  const skills = (index.skills || []).map((s) => ({
    name: s.name,
    title: s.title || s.name,
    category: s.category || "Uncategorized",
    path: s.path || null,
    persona: s.persona || null,
    triggers: Array.isArray(s.triggers) ? s.triggers : [],
  }));

  const modelsDoc = readYaml(SOURCES.model_profiles);
  const profiles = Object.entries(modelsDoc.profiles || {}).map(([id, p]) => ({
    id,
    description: (p && p.description) || "",
    provider: (p && p.provider) || "",
    primary: (p && p.primary) || null,
    use_for: (p && Array.isArray(p.use_for) && p.use_for) || [],
  }));

  const routingTree = modelsDoc.routing_tree || [];

  const promptsDoc = readYaml(SOURCES.agent_prompts);
  const promptTemplates = Object.keys(promptsDoc.prompts || {});
  const labelTriggers = promptsDoc.label_triggers || {};

  // Static require (reviewer-fleet finding: no dynamic require paths);
  // SOURCES.personas stays the documented source-of-truth pointer.
  const { PERSONA_REGISTRY } = require("./openrouter-personas.js");
  const personas = Object.values(PERSONA_REGISTRY).map((p) => ({
    handle: p.handle,
    name: p.name,
    emoji: p.emoji || "",
    role: p.role || "",
    aliases: (p.aliases || []).filter((a) => /[a-z]/i.test(a)),
    profile: p.profile || null,
    description: p.description || "",
  }));

  const fleetDoc = readYaml(SOURCES.fleet);
  const fleet = shapeFleet(fleetDoc);
  const securityFleet = shapeFleet(readYaml(SOURCES.security_fleet));

  return {
    schema_version: "1.0",
    vault_version: index.vault_version || null,
    repo: "midnghtsapphire/revvel-standards",
    sources: SOURCES,
    fleet,
    security_fleet: securityFleet,
    categories: [...new Set(skills.map((s) => s.category))].sort(),
    skills,
    profiles,
    routing_tree: routingTree,
    personas,
    prompt_templates: promptTemplates,
    label_triggers: labelTriggers,
  };
}

function main() {
  const args = process.argv.slice(2);
  const outIdx = args.indexOf("--out-dir");
  const outDir = outIdx >= 0 ? path.resolve(args[outIdx + 1]) : ROOT;

  const data = buildData();
  const json = JSON.stringify(data, null, 2) + "\n";
  fs.writeFileSync(path.join(outDir, "agent-creator-data.json"), json);
  fs.writeFileSync(
    path.join(outDir, "agent-creator-data.js"),
    "// Generated by scripts/build-agent-creator-data.js — do not edit.\n" +
      "window.AGENT_CREATOR_DATA = " +
      JSON.stringify(data) +
      ";\n"
  );
  console.log(
    `agent-creator data: ${data.skills.length} skills, ${data.profiles.length} profiles, ` +
      `${data.personas.length} personas -> ${path.relative(process.cwd(), outDir) || "."}`
  );
}

if (require.main === module) main();

module.exports = { buildData, SOURCES };
