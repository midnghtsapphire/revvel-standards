#!/usr/bin/env bash
# Install .git/hooks/pre-commit as a chained wrapper:
#   1) .pre-commit-hooks/pre-review-gate.sh   (this repo, auto-fix + validate)
#   2) any pre-existing wr/memory JSONL gate  (preserved)
set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

HOOK=".git/hooks/pre-commit"
GATE=".pre-commit-hooks/pre-review-gate.sh"
JSONL_GATE_CANDIDATES=(
  ".pre-commit-hooks/wr-memory-jsonl.sh"
  ".pre-commit-hooks/memory-jsonl.sh"
)

chmod +x "$GATE" 2>/dev/null || true

# Back up any existing unrelated hook.
if [ -f "$HOOK" ] && ! grep -q 'pre-review-gate.sh' "$HOOK"; then
  cp "$HOOK" "$HOOK.backup.$(date -u +%Y%m%dT%H%M%SZ)"
fi

{
  echo '#!/usr/bin/env bash'
  echo '# Auto-generated by scripts/setup-pre-review.sh — chained pre-commit gates.'
  echo 'set -e'
  echo 'REPO_ROOT="$(git rev-parse --show-toplevel)"'
  echo 'cd "$REPO_ROOT"'
  echo 'bash .pre-commit-hooks/pre-review-gate.sh'
  for c in "${JSONL_GATE_CANDIDATES[@]}"; do
    if [ -f "$c" ]; then
      echo "bash $c"
    fi
  done
} > "$HOOK"
chmod +x "$HOOK"

echo "Installed $HOOK"
