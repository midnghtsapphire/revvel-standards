#!/usr/bin/env bash
# Install .git/hooks/pre-commit as a thin wrapper that chains:
#   1. .pre-commit-hooks/pre-review-gate.sh (this repo)
#   2. any pre-existing wr/memory JSONL gate, if present
# Backs up any unrelated existing pre-commit hook.
set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOK_DIR="$REPO_ROOT/.git/hooks"
HOOK="$HOOK_DIR/pre-commit"
GATE=".pre-commit-hooks/pre-review-gate.sh"
JSONL_GATE=".pre-commit-hooks/wr-jsonl-gate.sh"

mkdir -p "$HOOK_DIR"
chmod +x "$REPO_ROOT/$GATE" 2>/dev/null || true
[ -f "$REPO_ROOT/$JSONL_GATE" ] && chmod +x "$REPO_ROOT/$JSONL_GATE" 2>/dev/null || true

if [ -f "$HOOK" ] && ! grep -q 'pre-review-gate.sh' "$HOOK" 2>/dev/null; then
  cp "$HOOK" "$HOOK.backup.$(date +%s)" 2>/dev/null || true
  echo "Backed up existing $HOOK"
fi

cat > "$HOOK" <<EOF
#!/usr/bin/env bash
# Auto-generated by scripts/setup-pre-review.sh — chains local gates.
set -e
ROOT="\$(git rev-parse --show-toplevel)"
if [ -f "\$ROOT/$GATE" ]; then
  bash "\$ROOT/$GATE" || exit \$?
fi
if [ -f "\$ROOT/$JSONL_GATE" ]; then
  bash "\$ROOT/$JSONL_GATE" || exit \$?
fi
exit 0
EOF

chmod +x "$HOOK"
echo "✓ Installed $HOOK (chains pre-review + JSONL gates)"
