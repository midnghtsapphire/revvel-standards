#!/usr/bin/env bash
# Install .git/hooks/pre-commit as a thin wrapper chaining the pre-review gate
# with any pre-existing wr/memory JSONL gate. Backs up unrelated existing hook.
set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOK="$REPO_ROOT/.git/hooks/pre-commit"
GATE="$REPO_ROOT/.pre-commit-hooks/pre-review-gate.sh"
JSONL_GATE="$REPO_ROOT/.pre-commit-hooks/wr-memory-jsonl.sh"

if [ ! -f "$GATE" ]; then
  echo "ERROR: gate script not found at $GATE" >&2
  exit 1
fi
chmod +x "$GATE"

if [ -f "$HOOK" ]; then
  # If the existing hook is not ours, back it up.
  if ! grep -q 'pre-review-gate.sh' "$HOOK" 2>/dev/null; then
    cp "$HOOK" "$HOOK.bak.$(date +%Y%m%d%H%M%S)"
    echo "backed up existing pre-commit hook"
  fi
fi

cat > "$HOOK" <<'HOOK'
#!/usr/bin/env bash
# Auto-generated by scripts/setup-pre-review.sh — chains repo hooks.
set -uo pipefail
REPO_ROOT="$(git rev-parse --show-toplevel)"
STATUS=0
if [ -f "$REPO_ROOT/.pre-commit-hooks/pre-review-gate.sh" ]; then
  bash "$REPO_ROOT/.pre-commit-hooks/pre-review-gate.sh" || STATUS=$?
fi
if [ "$STATUS" -eq 0 ] && [ -f "$REPO_ROOT/.pre-commit-hooks/wr-memory-jsonl.sh" ]; then
  bash "$REPO_ROOT/.pre-commit-hooks/wr-memory-jsonl.sh" || STATUS=$?
fi
exit "$STATUS"
HOOK
chmod +x "$HOOK"
echo "installed $HOOK"
