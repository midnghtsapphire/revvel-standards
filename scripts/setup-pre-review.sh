#!/usr/bin/env bash
# setup-pre-review.sh — install .git/hooks/pre-commit that chains
#   1) pre-review-gate.sh  (this repo)
#   2) any pre-existing wr/memory JSONL gate the repo already had
#
# Chained scripts are invoked via `bash` so checked-in file modes cannot
# break the hook. Any unrelated existing hook is backed up.

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOK_DIR="$REPO_ROOT/.git/hooks"
HOOK="$HOOK_DIR/pre-commit"
GATE=".pre-commit-hooks/pre-review-gate.sh"
JSONL_GATE=".pre-commit-hooks/jsonl-gate.sh"  # optional / repo-specific

mkdir -p "$HOOK_DIR"

if [ -f "$HOOK" ] && ! grep -q 'pre-review-gate' "$HOOK" 2>/dev/null; then
  cp "$HOOK" "$HOOK.backup.$(date +%s)"
  echo "Backed up existing pre-commit hook."
fi

cat > "$HOOK" <<'SH'
#!/usr/bin/env bash
# Auto-generated by scripts/setup-pre-review.sh
set -u
REPO_ROOT="$(git rev-parse --show-toplevel)"

run() {
  local script="$1"
  if [ -f "$REPO_ROOT/$script" ]; then
    bash "$REPO_ROOT/$script" || return $?
  fi
  return 0
}

run ".pre-commit-hooks/pre-review-gate.sh" || exit $?
run ".pre-commit-hooks/jsonl-gate.sh"     || exit $?

exit 0
SH

chmod +x "$HOOK"
chmod +x "$REPO_ROOT/$GATE" 2>/dev/null || true

echo "Installed pre-commit hook at $HOOK"
echo "Gate: $GATE"
if [ -f "$REPO_ROOT/$JSONL_GATE" ]; then
  echo "Chained gate: $JSONL_GATE"
fi
