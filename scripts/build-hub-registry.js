#!/usr/bin/env node
/**
 * build-hub-registry.js
 *
 * Website publication lane (issue #15510): builds the public-hub registry
 * consumed by index.html (the "Freedom Angel Corp — Public Hub" tab list)
 * from per-deliverable entry files, the same generated-not-hand-edited
 * pattern as scripts/build-agent-creator-data.js.
 *
 * Source of truth: data/hub/entries/*.json — one file per merged website
 * WR deliverable. Each entry:
 *
 *   {
 *     "slug": "my-page",              // unique id, kebab-case
 *     "title": "My Page",             // card heading (from the WR)
 *     "description": "What it does",  // card body (from the WR)
 *     "path": "./my-page/",           // repo-root-relative page path
 *     "tag": "Product",               // optional pill label (default "Website")
 *     "issue": 15510                  // source WR issue number (for the
 *                                     //  live-URL comment posted back)
 *   }
 *
 * Outputs (both generated, both committed):
 *   hub-registry.json — plain JSON, fetched when served over HTTP
 *   hub-registry.js   — window.HUB_REGISTRY wrapper so the hub also works
 *                       when index.html is opened as a local file
 *
 * The website-publish.yml workflow re-runs this on merge, commits the
 * refreshed registry, and comments the live Pages URL back on each entry's
 * WR issue — so the hub never drifts and never needs a hand edit.
 *
 * Usage: node scripts/build-hub-registry.js [--out-dir <dir>] [--entries-dir <dir>]
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ENTRIES_DIR = path.join(ROOT, "data", "hub", "entries");
const PAGES_BASE_URL = "https://midnghtsapphire.github.io/revvel-standards/";

const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
// Page paths must stay inside the repo (relative, no traversal) so the card
// link resolves under Pages/Vercel and can't point at arbitrary URLs.
const PATH_RE = /^\.\/(?!\.)[A-Za-z0-9._\-/]+$/;

function validateEntry(entry, file) {
  const fail = (msg) => {
    throw new Error(`${file}: ${msg}`);
  };
  if (!entry || typeof entry !== "object" || Array.isArray(entry)) fail("entry must be a JSON object");
  if (!SLUG_RE.test(entry.slug || "")) fail(`invalid slug ${JSON.stringify(entry.slug)} (kebab-case required)`);
  if (!entry.title || typeof entry.title !== "string") fail("missing title");
  if (!entry.description || typeof entry.description !== "string") fail("missing description");
  if (typeof entry.path !== "string" || !PATH_RE.test(entry.path) || entry.path.includes(".."))
    fail(`invalid path ${JSON.stringify(entry.path)} (must be repo-relative like "./my-page/")`);
  if (entry.issue !== undefined && (!Number.isInteger(entry.issue) || entry.issue <= 0))
    fail(`invalid issue ${JSON.stringify(entry.issue)} (positive integer expected)`);
  if (entry.tag !== undefined && typeof entry.tag !== "string") fail("tag must be a string");
}

function liveUrl(entryPath) {
  // "./my-page/" -> "https://midnghtsapphire.github.io/revvel-standards/my-page/"
  return PAGES_BASE_URL + entryPath.replace(/^\.\//, "");
}

function buildRegistry(entriesDir = ENTRIES_DIR) {
  const files = fs.existsSync(entriesDir)
    ? fs.readdirSync(entriesDir).filter((f) => f.endsWith(".json")).sort()
    : [];

  const seen = new Set();
  const entries = files.map((f) => {
    const raw = fs.readFileSync(path.join(entriesDir, f), "utf8");
    let entry;
    try {
      entry = JSON.parse(raw);
    } catch (e) {
      throw new Error(`${f}: invalid JSON (${e.message})`);
    }
    validateEntry(entry, f);
    if (seen.has(entry.slug)) throw new Error(`${f}: duplicate slug "${entry.slug}"`);
    seen.add(entry.slug);
    return {
      slug: entry.slug,
      title: entry.title,
      description: entry.description,
      path: entry.path,
      tag: entry.tag || "Website",
      issue: entry.issue || null,
      live_url: liveUrl(entry.path),
    };
  });

  return {
    schema_version: "1.0",
    repo: "midnghtsapphire/revvel-standards",
    generated_by: "scripts/build-hub-registry.js",
    pages_base_url: PAGES_BASE_URL,
    entries,
  };
}

function main() {
  const args = process.argv.slice(2);
  const outIdx = args.indexOf("--out-dir");
  const outDir = outIdx >= 0 ? path.resolve(args[outIdx + 1]) : ROOT;
  const entIdx = args.indexOf("--entries-dir");
  const entriesDir = entIdx >= 0 ? path.resolve(args[entIdx + 1]) : ENTRIES_DIR;

  const data = buildRegistry(entriesDir);
  fs.writeFileSync(path.join(outDir, "hub-registry.json"), JSON.stringify(data, null, 2) + "\n");
  fs.writeFileSync(
    path.join(outDir, "hub-registry.js"),
    "// Generated by scripts/build-hub-registry.js — do not edit.\n" +
      "window.HUB_REGISTRY = " +
      JSON.stringify(data) +
      ";\n"
  );
  console.log(
    `hub registry: ${data.entries.length} entries -> ${path.relative(process.cwd(), outDir) || "."}`
  );
}

if (require.main === module) main();

module.exports = { buildRegistry, validateEntry, liveUrl, ENTRIES_DIR, PAGES_BASE_URL };
