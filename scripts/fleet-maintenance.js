#!/usr/bin/env node
"use strict";

/**
 * Fleet Maintenance Sweep
 *
 * Walks every repository in the owner account, and for a capped, rotating subset
 * each run opens a DRAFT pull request that:
 *   - refreshes / creates docs/IMPROVEMENTS.md with a Professor-researched plan
 *     (concrete doc updates + improvement ideas for that repo), and
 *   - is left as a draft for human review (nothing auto-merges).
 *
 * Safety rails:
 *   - DRY_RUN=true (default for scheduled runs until trusted) only logs the plan.
 *   - No-ops cleanly if FLEET_TOKEN is missing.
 *   - MAX_REPOS caps repos touched per run; selection rotates by ISO week so the
 *     whole fleet is covered over time without doing everything at once.
 *   - Skips a repo that already has an open fleet-maintenance PR (idempotent).
 *   - Skips archived repos and forks.
 *
 * Code implementation (beyond docs) is intentionally NOT done here yet — enable
 * it deliberately per repo once the sweep is trusted.
 *
 * Env:
 *   FLEET_TOKEN          PAT with repo access across the org (e.g. ADMIN_GITHUB_TOKEN)
 *   OWNER                account/org to sweep (default: midnghtsapphire)
 *   OPENROUTER_API_KEY   optional; enables Professor research (falls back to a template)
 *   MAX_REPOS            cap per run (default 5)
 *   DRY_RUN              'true' to log the plan without cloning or opening PRs
 */

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const BRANCH_PREFIX = "fleet/maintenance";
const DOC_PATH = "docs/IMPROVEMENTS.md";

function env(key, def = "") {
  return process.env[key] || def;
}

function gh(args, options = {}) {
  return execFileSync("gh", args, { encoding: "utf8", ...options });
}

function git(args, cwd) {
  return execFileSync("git", args, { encoding: "utf8", cwd });
}

function isoWeek(date = new Date()) {
  const d = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  const dayNum = (d.getUTCDay() + 6) % 7;
  d.setUTCDate(d.getUTCDate() - dayNum + 3);
  const firstThursday = new Date(Date.UTC(d.getUTCFullYear(), 0, 4));
  return 1 + Math.round(((d - firstThursday) / 86400000 - 3 + ((firstThursday.getUTCDay() + 6) % 7)) / 7);
}

/**
 * Pick a stable, rotating subset so the whole fleet is covered over time.
 * Pure function — unit tested.
 *
 * @param {string[]} repoNames - candidate repo names (already filtered).
 * @param {number} week - ISO week number used as the rotation offset.
 * @param {number} max - max repos to return.
 * @returns {string[]}
 */
function selectRepos(repoNames, week, max) {
  if (!Array.isArray(repoNames) || repoNames.length === 0) return [];
  const sorted = [...repoNames].sort();
  if (max >= sorted.length) return sorted;
  const start = (week * max) % sorted.length;
  const out = [];
  for (let i = 0; i < max; i++) {
    out.push(sorted[(start + i) % sorted.length]);
  }
  return out;
}

function listRepos(owner) {
  const raw = gh([
    "repo", "list", owner,
    "--no-archived", "--source", "--limit", "1000",
    "--json", "name,isFork,isArchived",
  ]);
  const repos = JSON.parse(raw || "[]");
  return repos.filter((r) => !r.isFork && !r.isArchived).map((r) => r.name);
}

function hasOpenFleetPR(owner, repo) {
  try {
    const raw = gh([
      "pr", "list", "--repo", `${owner}/${repo}`,
      "--state", "open", "--json", "headRefName",
    ]);
    const prs = JSON.parse(raw || "[]");
    return prs.some((p) => (p.headRefName || "").startsWith(BRANCH_PREFIX));
  } catch {
    return false;
  }
}

async function researchPlan(repo, readme) {
  const fallback = [
    `# Improvement Plan — ${repo}`,
    "",
    "_Auto-generated by the fleet-maintenance sweep. Review and refine._",
    "",
    "## Docs",
    "- [ ] Ensure README states what the project is, how to run it, and how to contribute.",
    "- [ ] Add/refresh a short architecture overview.",
    "",
    "## Improvements to research",
    "- [ ] Dependency updates and known CVEs.",
    "- [ ] Test coverage gaps.",
    "- [ ] CI/CD hardening.",
    "",
  ].join("\n");

  if (!env("OPENROUTER_API_KEY")) return fallback;
  try {
    const { instantiate } = require("./openrouter-personas");
    const task =
      `Repository: ${repo}.\n\nREADME (truncated):\n${(readme || "(none)").slice(0, 4000)}\n\n` +
      "Produce a concise, actionable improvement plan in Markdown: (1) specific documentation " +
      "updates this repo needs, and (2) concrete, researched ways to make it better (deps, security, " +
      "tests, DX, performance). Use checkbox lists. Cite sources where you make factual claims.";
    const result = await instantiate("professor", { mode: "eager", task, silent: true });
    return `# Improvement Plan — ${repo}\n\n_Researched by The Professor (${result.modelUsed || "model"}). Review before acting._\n\n${result.text}\n`;
  } catch (err) {
    console.log(`  research failed (${err.message}); using template.`);
    return fallback;
  }
}

async function processRepo(owner, repo, token, dryRun) {
  if (hasOpenFleetPR(owner, repo)) {
    console.log(`• ${repo}: open fleet PR already exists — skipping.`);
    return false;
  }
  if (dryRun) {
    console.log(`• ${repo}: [dry-run] would open a draft docs/improvement PR.`);
    return false;
  }

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), `fleet-${repo}-`));
  const url = `https://x-access-token:${token}@github.com/${owner}/${repo}.git`;
  git(["clone", "--depth", "1", url, tmp]);

  let readme = "";
  for (const name of ["README.md", "readme.md", "README.MD"]) {
    const p = path.join(tmp, name);
    if (fs.existsSync(p)) { readme = fs.readFileSync(p, "utf8"); break; }
  }

  const branch = `${BRANCH_PREFIX}-${new Date().toISOString().slice(0, 10)}`;
  git(["checkout", "-b", branch], tmp);
  const plan = await researchPlan(repo, readme);
  fs.mkdirSync(path.join(tmp, "docs"), { recursive: true });
  fs.writeFileSync(path.join(tmp, DOC_PATH), plan);
  git(["add", DOC_PATH], tmp);
  git(["-c", "user.name=fleet-maintenance", "-c", "user.email=fleet@users.noreply.github.com",
       "commit", "-m", "docs: fleet-maintenance improvement plan"], tmp);
  git(["push", "-u", "origin", branch], tmp);

  gh(["pr", "create", "--repo", `${owner}/${repo}`, "--draft",
      "--title", "Fleet maintenance: docs + improvement plan",
      "--body", "Auto-filed by the fleet-maintenance sweep. Refreshes `docs/IMPROVEMENTS.md` with a researched plan. **Draft — review before merge.**"]);
  console.log(`• ${repo}: opened draft PR on ${branch}.`);
  return true;
}

async function main() {
  const token = env("FLEET_TOKEN");
  if (!token) {
    console.log("::warning::FLEET_TOKEN not set — fleet maintenance skipped (no failure).");
    return 0;
  }
  process.env.GH_TOKEN = token;

  const owner = env("OWNER", "midnghtsapphire");
  const maxRepos = Math.max(1, parseInt(env("MAX_REPOS", "5"), 10) || 5);
  const dryRun = env("DRY_RUN", "").toLowerCase() === "true";

  const repos = listRepos(owner);
  const selected = selectRepos(repos, isoWeek(), maxRepos);
  console.log(`${repos.length} repo(s) in ${owner}; sweeping ${selected.length} this run (DRY_RUN=${dryRun}): ${selected.join(", ")}`);

  let opened = 0;
  for (const repo of selected) {
    try {
      if (await processRepo(owner, repo, token, dryRun)) opened++;
    } catch (err) {
      console.log(`• ${repo}: error — ${err.message}`);
    }
  }
  console.log(`Done. Opened ${opened} draft PR(s).`);
  return 0;
}

if (require.main === module) {
  main().then((c) => process.exit(c)).catch((e) => { console.error("Error:", e.message); process.exit(1); });
}

module.exports = { selectRepos, isoWeek };
