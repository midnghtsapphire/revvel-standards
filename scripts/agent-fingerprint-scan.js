#!/usr/bin/env node
'use strict';

// agent-fingerprint-scan.js — block agent watermarks, scaffolding leftovers,
// and unsolicited READMEs from shipping in PRs. Pure Node, no shell.
//
// Usage:
//   node scripts/agent-fingerprint-scan.js <file> [<file>...]   # scan args
//   node scripts/agent-fingerprint-scan.js --changed             # read from stdin (CI)
//
// Exits 0 = clean, 1 = at least one fingerprint hit.
// Standard: standards/AGENT_SCAFFOLDING_BAN.md

const fs = require('fs');
const path = require('path');

// ── Banned patterns. Each is { id, re, why, allowedFiles? } ───────────────────
// `allowedFiles`: paths matching any regex here are exempt for that rule.
const BANNED = [
  // ── A. Attribution / "Made with" footers ────────────────────────────────────
  { id: 'lovable-attr', re: /Made with Lovable|Built on Lovable|Powered by Lovable/i, why: 'Lovable attribution string' },
  { id: 'replit-attr',  re: /Made with Replit|Built on Replit|Powered by Replit/i,    why: 'Replit attribution string' },
  { id: 'manus-attr',   re: /Made with Manus|Powered by Manus/i,                       why: 'Manus attribution string' },
  { id: 'bolt-attr',    re: /Made with Bolt|Powered by Bolt/i,                         why: 'Bolt attribution string' },
  { id: 'v0-attr',      re: /Made with v0\b|Built with v0\b/i,                           why: 'v0 attribution string' },
  { id: 'cursor-attr',  re: /Generated by Cursor/i,                                    why: 'Cursor attribution string' },
  { id: 'claude-gen-attr', re: /Generated by Claude/i,                                  why: 'Claude attribution string (per standard)' },
  { id: 'gpt-gen-attr',    re: /Generated by GPT/i,                                     why: 'GPT attribution string' },
  { id: 'bolt-url',     re: /\bbolt\.new\b/i,                                            why: 'bolt.new URL in user-facing copy' },
  { id: 'v0-url',       re: /\bv0\.dev\b/i,                                              why: 'v0.dev URL in user-facing copy' },
  {
    id: 'claude-attr-user-facing',
    re: /Co-Authored-By: Claude/i,
    why: 'Claude attribution in a user-facing file (allowed in git commit messages only)',
    // Allowed in markdown docs about the agent itself + any .md inside docs/ — git
    // commit messages are NOT in files, so the user-facing scope here is correct.
    allowedFiles: [/^docs\//, /^standards\//, /^\.github\//, /^CHANGELOG\.md$/i],
  },

  // ── B. Default scaffolding pages ────────────────────────────────────────────
  { id: 'vite-default-welcome', re: /Welcome to Vite\b|Vite \+ React\s*\+ TypeScript/i, why: 'Vite default starter welcome text — replace before shipping' },
  { id: 'vite-counter',         re: /count is 0|setCount\(\(count\) => count \+ 1\)/, why: 'Vite/CRA default counter component — replace before shipping' },
  { id: 'cra-bootstrap-readme', re: /This project was bootstrapped with Create React App/i, why: 'CRA boilerplate README — generate one when actually needed, not by default' },
  { id: 'next-getting-started', re: /Get started by editing.*pages\/index|Get started by editing.*app\/page/i, why: 'Next.js default starter page — replace before shipping' },

  // ── C. Unused test scaffolding ──────────────────────────────────────────────
  { id: 'cra-test-renders-learn', re: /renders learn react link/i, why: 'CRA default test (renders learn react link) — replace with a real test' },
  { id: 'cra-test-renders-vite',  re: /renders Vite \+ React/i,    why: 'Vite default test — replace with a real test' },

  // ── D. Unrequested README boilerplate ──────────────────────────────────────
  { id: 'vite-readme-available-scripts', re: /## Available Scripts\s+In the project directory/i, why: 'CRA-style README "Available Scripts" block — unsolicited boilerplate' },
  { id: 'vite-readme-learn-more',        re: /## Learn More\s+You can learn more in/i,           why: 'CRA-style README "Learn More" block — unsolicited boilerplate' },
  { id: 'deploy-on-vercel-readme',       re: /## Deploy on Vercel\s+The easiest way to deploy/i, why: 'Vercel-generated README block — unsolicited boilerplate' },

  // ── E. Watermarked SVG/asset comments ──────────────────────────────────────
  { id: 'svg-comment-watermark', re: /<!-- (Generated by|Created with) (Manus|Lovable|Replit|Bolt|v0|Cursor|Claude) -->/i, why: 'Asset watermark comment from generator' },
];

// Skip directories AND files that are explicitly about agent fingerprints
// (the standard doc + per-agent profiles must be able to quote the banned
// strings as examples).
const SKIP_DIRS = [/^node_modules\//, /^dist\//, /^build\//, /^\.next\//, /^out\//, /^public\/build\//, /^coverage\//, /^\.git\//];
const SKIP_FILES = [
  /^standards\/AGENT_SCAFFOLDING_BAN\.md$/,
  /^docs\/agents\/[^/]+\/PROFILE\.md$/,
  /^docs\/agents\/README\.md$/,
  /^docs\/agents\/[^/]+\/transcripts\//,    // captured sessions can quote bans
  /^scripts\/agent-fingerprint-scan\.js$/,
  /^\.github\/workflows\/agent-fingerprint-gate\.yml$/,
  /^CONTRIBUTING\.md$/i,                     // dev docs may credit agents
  /^docs\/.+\.md$/i,                         // all dev docs may quote bans
];
const SCAN_EXTS = new Set(['.md', '.mdx', '.txt', '.html', '.svg', '.tsx', '.jsx', '.ts', '.js', '.mjs', '.cjs', '.vue', '.svelte', '.css', '.scss', '.json', '.yaml', '.yml']);

function skipPath(p) {
  if (SKIP_DIRS.some(r => r.test(p))) return true;
  if (SKIP_FILES.some(r => r.test(p))) return true;
  return false;
}
function shouldScan(p) {
  if (skipPath(p)) return false;
  const ext = path.extname(p).toLowerCase();
  return SCAN_EXTS.has(ext);
}

function scan(file) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); }
  catch (e) {
    // Per Copilot review: fail closed on unreadable. Submodules, dangling
    // symlinks, encoding issues, permission errors — any of which could be
    // used to smuggle fingerprints — now register as a hit so CI surfaces it.
    return [{ file, line: 0, id: 'unreadable', snippet: e.code || e.message, why: 'file is unreadable — failing closed (CI must surface)' }];
  }
  const hits = [];
  for (const rule of BANNED) {
    if (rule.allowedFiles && rule.allowedFiles.some(r => r.test(file))) continue;
    const m = rule.re.exec(text);
    if (m) {
      const before = text.slice(0, m.index);
      const line = before.split('\n').length;
      hits.push({ file, line, id: rule.id, snippet: m[0].slice(0, 80), why: rule.why });
    }
  }
  return hits;
}

function readChangedFromStdin() {
  return new Promise(resolve => {
    const chunks = [];
    process.stdin.on('data', c => chunks.push(c));
    process.stdin.on('end', () => {
      resolve(Buffer.concat(chunks).toString('utf8').split('\n').filter(Boolean));
    });
  });
}

module.exports = { scan, shouldScan, skipPath, BANNED };

if (require.main === module) {
  (async function main() {
    const args = process.argv.slice(2);
    let files;
    const useStdin = args.includes('--changed');
    const positional = args.filter(a => a !== '--changed');
    if (useStdin && positional.length) {
      // Per Octopus review: silently dropping positional args when --changed is
      // also present was confusing. Error out instead.
      console.error('error: --changed cannot be combined with positional file args');
      process.exit(2);
    }
    if (useStdin) {
      files = (await readChangedFromStdin()).map(f => f.trim()).filter(Boolean);
    } else if (positional.length) {
      files = positional;
    } else {
      console.error('usage: node scripts/agent-fingerprint-scan.js <file...> | --changed');
      process.exit(2);
    }

    files = files.filter(shouldScan);
    const allHits = [];
    for (const f of files) allHits.push(...scan(f));

    if (allHits.length === 0) {
      console.log(`✓ agent-fingerprint-scan: clean (${files.length} file(s) scanned)`);
      process.exit(0);
    }
    console.log(`✗ agent-fingerprint-scan: ${allHits.length} hit(s)`);
    for (const h of allHits) {
      console.log(`  ${h.file}:${h.line}  [${h.id}]  ${h.why}`);
      console.log(`      "${h.snippet}"`);
    }
    console.log(`\nStandard: standards/AGENT_SCAFFOLDING_BAN.md`);
    console.log(`Exception: add 'agent-fingerprint:allow <reason>' to the PR body.`);
    process.exit(1);
  })();
}
