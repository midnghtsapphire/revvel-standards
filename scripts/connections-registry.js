/** Find integrations present in the repo but missing from the registry. Pure. */
function detectDrift(doc, repoInventory) {
  const known = new Set();
  for (const c of doc.connections) {
    if (c.id) known.add(c.id.toLowerCase());
    if (c.env) known.add(c.env.toLowerCase());
    if (c.name) known.add(c.name.toLowerCase());
  }
  const missing = [];
  for (const item of repoInventory) {
    const key = item.key.toLowerCase();
    const matched =
      known.has(key) ||
      [...known].some((k) => k.includes(key) || key.includes(k));
    if (!matched) missing.push(item);
  }
  return missing;
}

function scanRepoInventory() {
  const inv = [];
  // API keys from .env.example
  const envPath = path.join(ROOT, '.env.example');
  if (fs.existsSync(envPath)) {
    for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
      const m = line.match(/^([A-Z0-9_]+)_API_KEY\s*=/);
      if (m) inv.push({ key: m[1].replace(/_/g, '-'), source: '.env.example' });
    }
  }
  return inv;
}

function main(argv = process.argv.slice(2)) {
  const doc = load();
  const wantHtml = argv.includes('--html') || argv.includes('--all') || argv.length === 0;
  const wantMd = argv.includes('--markdown') || argv.includes('--all') || argv.length === 0;
  const wantDrift = argv.includes('--drift');

  if (wantMd) {
    fs.writeFileSync(DOC_PATH, renderMarkdown(doc));
    if (fs.existsSync(README_PATH)) {
      const readme = fs.readFileSync(README_PATH, 'utf8');
      let next = injectReadme(readme, renderReadmeBlock(doc));
      next = injectReadme(next, renderFallbackBlock(doc), FB_BEGIN, FB_END);
      if (next !== readme) fs.writeFileSync(README_PATH, next);
    }
    console.log(`✅ wrote ${path.relative(ROOT, DOC_PATH)} (+ README block)`);
  }
  if (wantHtml) {
    fs.writeFileSync(HTML_PATH, renderHtml(doc));
    console.log(`✅ wrote ${path.relative(ROOT, HTML_PATH)}`);
  }
  if (wantDrift) {
    const missing = detectDrift(doc, scanRepoInventory());
    if (missing.length) {
      console.log(`⚠️ ${missing.length} integration(s) in the repo but missing from config/connections.yml:`);
      for (const m of missing) console.log(`   - ${m.key} (${m.source})`);
      if (argv.includes('--strict')) process.exitCode = 1;
    } else {
      console.log('✅ no drift — registry covers the repo inventory.');
    }
  }
}

module.exports = {
  BEGIN, END, FB_BEGIN, FB_END,
  load, groupByType, renderMarkdown, renderReadmeBlock, renderFallbackBlock,
  injectReadme, renderHtml, detectDrift, scanRepoInventory, main,
};

if (require.main === module) main();
