#!/usr/bin/env node
'use strict';

/**
 * Connections Registry generator.
 *
 * SSOT is config/connections.yml. This renders always-fresh views so the docs
 * can never drift from reality:
 *   - docs/CONNECTIONS_REGISTRY.md   (grouped tables)
 *   - README.md block between <!-- BEGIN:connections --> / <!-- END:connections -->
 *   - connections-dashboard.html     (on-demand, filterable functional dashboard)
 *   - drift report (integrations present in the repo but missing from the SSOT)
 *
 * Pure render/group/inject/drift functions are exported for tests; IO lives in main().
 */

const fs = require('fs');
const path = require('path');
const YAML = require('yaml');

const ROOT = path.join(__dirname, '..');
const REGISTRY_PATH = path.join(ROOT, 'config/connections.yml');
const DOC_PATH = path.join(ROOT, 'docs/CONNECTIONS_REGISTRY.md');
const HTML_PATH = path.join(ROOT, 'connections-dashboard.html');
const README_PATH = path.join(ROOT, 'README.md');

const BEGIN = '<!-- BEGIN:connections -->';
const END = '<!-- END:connections -->';
const FB_BEGIN = '<!-- BEGIN:fallback -->';
const FB_END = '<!-- END:fallback -->';

const TYPE_ORDER = ['agent', 'mcp', 'api', 'cli', 'library', 'github-action', 'app', 'model'];
const TYPE_TITLE = {
  agent: 'Agents & orchestration',
  mcp: 'MCP servers',
  api: 'APIs',
  cli: 'CLIs',
  library: 'Libraries',
  'github-action': 'GitHub Actions',
  app: 'GitHub apps / bots',
  model: 'Models',
};

function load(registryPath = REGISTRY_PATH) {
  const doc = YAML.parse(fs.readFileSync(registryPath, 'utf8'));
  return doc && Array.isArray(doc.connections) ? doc : { meta: {}, connections: [] };
}

function groupByType(connections) {
  const groups = new Map();
  for (const c of connections) {
    const t = c.type || 'other';
    if (!groups.has(t)) groups.set(t, []);
    groups.get(t).push(c);
  }
  return groups;
}

function list(arr) {
  return Array.isArray(arr) && arr.length ? arr.join(', ') : '—';
}
/** Build a markdown table row with single-spaced, trimmed cells (MD060-safe). */
/**
 * Render a note field for the Markdown table.
 *
 * Two escapes, both required by the table this feeds:
 *
 *   1. `|` would end the table cell early.
 *   2. A bare URL trips MD034/no-bare-urls. That matters more than it looks:
 *      this table is generated, and CircleCI's lint-and-test gate lints
 *      *changed* Markdown — so a single bare URL typed into a note in
 *      config/connections.yml turns docs/CONNECTIONS_REGISTRY.md red for
 *      every PR that regenerates it, with the error pointing at the generated
 *      file rather than at the note that caused it.
 *
 * Angle brackets are the autolink form MD034 asks for. URLs already wrapped
 * in <> or already inside a [text](url) link are left alone, and trailing
 * sentence punctuation is kept outside the link.
 */
function mdNote(note) {
  return String(note || '—')
    .replace(/\|/g, '\\|')
    .replace(/(^|[^<(\[])(https?:\/\/[^\s<>()]*[^\s<>().,;:!?])/g, (m, pre, url) => `${pre}<${url}>`);
}

function row(cells) {
  return `| ${cells.map((c) => String(c).trim()).join(' | ')} |`;
}
function statusBadge(s) {
  return s === 'verified' ? '✅ verified' : s === 'unverified' ? '⚠️ unverified' : '❔';
}

function renderMarkdown(doc) {
  const conns = doc.connections;
  const groups = groupByType(conns);
  const verified = conns.filter((c) => c.status === 'verified').length;
  const unverified = conns.filter((c) => c.status === 'unverified').length;

  const out = [];
  out.push('<!-- generated by scripts/connections-registry.js from config/connections.yml — do not edit by hand -->');
  out.push('# Connections Registry');
  out.push('');
  out.push(
    'Every tool, API, MCP server, CLI, agent, and GitHub app in the fleet, and what ' +
      'each can reach. **Generated from `config/connections.yml`** — edit the YAML, ' +
      'run `npm run connections`, never hand-edit this file.'
  );
  out.push('');
  out.push(`**${conns.length}** connections · **${verified}** verified · **${unverified}** unverified (confirm before relying on them).`);
  out.push('');

  for (const type of [...TYPE_ORDER, ...[...groups.keys()].filter((t) => !TYPE_ORDER.includes(t))]) {
    const items = groups.get(type);
    if (!items || !items.length) continue;
    out.push(`## ${TYPE_TITLE[type] || type}`);
    out.push('');
    out.push(row(['Name', 'Status', 'Auth', 'Can access', 'Connects to', 'Used by', 'Notes']));
    out.push('| --- | :---: | :---: | --- | --- | --- | --- |');
    for (const c of items.sort((a, b) => (a.name || '').localeCompare(b.name || ''))) {
      out.push(
        row([
          c.name ? `\`${c.id}\` (${c.name})` : `\`${c.id}\``,
          statusBadge(c.status),
          c.auth || '—',
          list(c.access),
          list(c.connects_to),
          list(c.used_by),
          mdNote(c.note),
        ])
      );
    }
    out.push('');
  }
  out.push(`*Last generated: ${new Date().toISOString().slice(0, 10)} from \`config/connections.yml\`.*`);
  return out.join('\n') + '\n';
}

/** Compact summary table for the README block. */
function renderReadmeBlock(doc) {
  const conns = doc.connections;
  const groups = groupByType(conns);
  const verified = conns.filter((c) => c.status === 'verified').length;
  const lines = [];
  lines.push(BEGIN);
  lines.push('### 🔌 Connections at a glance');
  lines.push('');
  lines.push(`${conns.length} wired integrations (${verified} verified). Full table: [docs/CONNECTIONS_REGISTRY.md](docs/CONNECTIONS_REGISTRY.md) · on-demand dashboard: [connections-dashboard.html](connections-dashboard.html). SSOT: \`config/connections.yml\`.`);
  lines.push('');
  lines.push('| Category | Count | Examples |');
  lines.push('| --- | ---: | --- |');
  for (const type of [...TYPE_ORDER, ...[...groups.keys()].filter((t) => !TYPE_ORDER.includes(t))]) {
    const items = groups.get(type);
    if (!items || !items.length) continue;
    const examples = items.slice(0, 4).map((c) => `\`${c.id}\``).join(', ');
    lines.push(`| ${TYPE_TITLE[type] || type} | ${items.length} | ${examples}${items.length > 4 ? ', …' : ''} |`);
  }
  lines.push('');
  lines.push(END);
  return lines.join('\n');
}

/** Replace the block between a marker pair. No-op if the markers are absent. Pure. */
function injectReadme(readme, block, begin = BEGIN, end = END) {
  if (readme.includes(begin) && readme.includes(end)) {
    const re = new RegExp(`${begin}[\\s\\S]*?${end}`);
    return readme.replace(re, block);
  }
  // Only the connections block falls back to auto-insert before the first rule.
  if (begin === BEGIN) return readme.replace(/\n(---\n)/, `\n\n${block}\n\n$1`);
  return readme;
}

/** Generated agent-fallback chain block for the README (replaces stale prose). */
function renderFallbackBlock(doc) {
  const chain = (doc.meta && doc.meta.fallback_chain) || [];
  const retired = (doc.meta && doc.meta.fallback_retired) || [];
  const lines = [FB_BEGIN];
  lines.push('**Fallback chain** — generated from `config/connections.yml`, so it never drifts:');
  lines.push('');
  chain.forEach((step, i) => {
    lines.push(`${i + 1}. **${step.id}** — *${step.role}* — ${step.note}`);
  });
  if (retired.length) {
    lines.push('');
    lines.push(`*Retired: ${retired.map((r) => `\`${r.id}\` (${r.note})`).join('; ')}*`);
  }
  lines.push(FB_END);
  return lines.join('\n');
}

